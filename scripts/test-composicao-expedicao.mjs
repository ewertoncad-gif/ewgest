import assert from 'node:assert/strict';
import {validarComposicao,calcularSaldo,expandirCompleta,areaExpedida,sugerirSimilares} from '../assets/composicao-expedicao-core.mjs';
const p=[{id:'m',nome:'Marco',quantidade:1,peso:5000},{id:'f',nome:'Folha',quantidade:2,peso:5000}];
const perto=(x,y)=>assert.ok(Math.abs(x-y)<1e-10);
assert.equal(calcularSaldo(p,2).linhas[1].saldo,4);
for(let q=1;q<=4;q++)perto(areaExpedida(p,2,[{id:'f',quantidade:q}],1200,1150),q*0.345);
assert.equal(calcularSaldo(p,2,[{id:'f',quantidade:3}]).linhas[1].saldo,1);
assert.equal(calcularSaldo(p,2,[{id:'f',quantidade:3}]).completas,0);
assert.throws(()=>calcularSaldo(p,2,[{id:'f',quantidade:5}]));
assert.equal(calcularSaldo(p,2,[{id:'f',quantidade:3,cancelada:true}]).linhas[1].saldo,4);
const maxim=[{id:'m',nome:'Marco',quantidade:1,peso:5000},{id:'f',nome:'Folha',quantidade:1,peso:4000},{id:'v',nome:'Vidro do peitoril',quantidade:1,peso:1000}];
perto(areaExpedida(maxim,1,[{id:'f',quantidade:1}],1000,1000),0.4);
perto(areaExpedida(maxim,1,expandirCompleta(maxim,1),1000,1000),1);
const agrupado=[{id:'mv',nome:'Marco com vidro',quantidade:1,peso:5000},{id:'f',nome:'Folha',quantidade:1,peso:5000}];
perto(areaExpedida(agrupado,1,[{id:'mv',quantidade:1}],1000,1000),0.5);
assert.throws(()=>validarComposicao(maxim.slice(0,2)));
assert.throws(()=>validarComposicao([{...maxim[0],peso:10000,quantidade:0}]));
assert.throws(()=>validarComposicao([{...maxim[0],peso:5000},{...maxim[0],peso:5000}]));
const origem={id:'a',empresa_id:'e',codigo:'A',descricao:'MAXIM-AR COM PEITORIL FIXO - LINHA A - FAB A',fabricante:'FAB A'};
const catalogo=[{...origem,id:'b',codigo:'B',descricao:'MAXIM AR PEITORIL FIXO - LINHA B - FAB B',fabricante:'FAB B'},{...origem,id:'c',descricao:'MAXIM-AR - LINHA C'},{...origem,id:'d',empresa_id:'outra'},{...origem,id:'e',quantidade_modulos:2}];
assert.deepEqual(sugerirSimilares(origem,catalogo).map(x=>x.id),['b']);
console.log('OK: composição 50/50, 50/40/10, folhas físicas, estorno, limites e similares.');
